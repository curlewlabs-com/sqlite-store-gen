#!/usr/bin/env bun
// The command line: read one spec, render it, and write the three sources where the
// caller says.

import { mkdir, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { parseArgs } from "node:util";
import type { LocalSQLiteRenderOptions } from "./options";
import { renderLocalSQLiteSources } from "./render";
import { loadLocalSQLiteSpec } from "./spec";

const USAGE = `usage: sqlite-store-gen <spec.json>
  --kotlin-package <package>     package of the generated Kotlin file
  --database-file-name <name>    file name of the store on disk
  --kotlin-out <path>            where to write the Kotlin source
  --swift-out <path>             where to write the Swift source
  --dart-out <path>              where to write the Dart channel constants
  [--notice <text>]              header written at the top of each file, verbatim`;

function required(
  values: Record<string, string | undefined>,
  name: string,
): string {
  const value = values[name];
  if (value === undefined || value.length === 0) {
    throw new Error(`--${name} is required\n${USAGE}`);
  }
  return value;
}

async function main(argv: string[]): Promise<void> {
  const { values, positionals } = parseArgs({
    args: argv,
    allowPositionals: true,
    options: {
      "kotlin-package": { type: "string" },
      "database-file-name": { type: "string" },
      notice: { type: "string" },
      "kotlin-out": { type: "string" },
      "swift-out": { type: "string" },
      "dart-out": { type: "string" },
    },
  });
  const specPath = positionals[0];
  if (specPath === undefined || positionals.length !== 1) {
    throw new Error(USAGE);
  }
  const options: LocalSQLiteRenderOptions = {
    kotlinPackage: required(values, "kotlin-package"),
    databaseFileName: required(values, "database-file-name"),
    notice:
      values.notice ??
      `// Generated by sqlite-store-gen from ${specPath}. Do not edit by hand.`,
  };
  const outputs = {
    kotlin: required(values, "kotlin-out"),
    swift: required(values, "swift-out"),
    dart: required(values, "dart-out"),
  };

  const sources = renderLocalSQLiteSources(
    await loadLocalSQLiteSpec(specPath),
    options,
  );
  for (const kind of ["kotlin", "swift", "dart"] as const) {
    await mkdir(dirname(outputs[kind]), { recursive: true });
    await writeFile(outputs[kind], sources[kind], "utf-8");
    console.log(`wrote ${outputs[kind]}`);
  }
}

if (import.meta.main) {
  main(process.argv.slice(2)).catch((error: unknown) => {
    console.error("sqlite-store-gen failed:", error);
    process.exitCode = 1;
  });
}
